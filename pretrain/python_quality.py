"""Pure, source-text-free quality metrics for bounded Python inspections.

The functions in this module perform no network or filesystem I/O.  They accept
already-resolved bytes/text, return JSON-safe aggregate evidence, and never
return source text, source lines, identifiers, literals, or paths.  All
canonicalization is detection-only: retained training text is not rewritten.
"""

