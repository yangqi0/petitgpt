def _canonical_json_bytes(value: Any) -> bytes:
    return json.dumps(
        value,
        allow_nan=False,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")


def _sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def _git_head() -> str:
    result = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=PROJECT_ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    return result.stdout.strip()


def _ensure_revision(value: str) -> str:
    if not _REVISION_RE.fullmatch(value):
        raise GateEError("source revision must be an exact lowercase 40-hex commit")
    return value


def _ensure_under_workspace(path: Path) -> Path:
    resolved = path.resolve(strict=False)
    try:
        resolved.relative_to(PROJECT_ROOT)
    except ValueError as exc:
        raise GateEError("all Gate E paths must remain under the repository") from exc
    return resolved


def _ensure_git_ignored(path: Path) -> None:
    resolved = _ensure_under_workspace(path)
    relative = resolved.relative_to(PROJECT_ROOT)
    result = subprocess.run(
        ["git", "check-ignore", "--quiet", "--no-index", "--", str(relative)],
        cwd=PROJECT_ROOT,
        check=False,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise GateEError(f"Gate E output/cache path is not Git-ignored: {relative}")


def _validate_inspection_config(config: InspectionConfig, staging: Path) -> None:
    _ensure_revision(config.source.revision)
    if not 1 <= config.documents <= config.source.inspection_cap:
        raise GateEError(
            f"documents must be in [1, {config.source.inspection_cap}] for {config.source.key}"
        )
    if not 20 <= config.accepted_snippets <= 30:
        raise GateEError("accepted_snippets must be in [20, 30]")
    if not 10 <= config.rejected_snippets <= 15:
        raise GateEError("rejected_snippets must be in [10, 15]")
    if not 1 <= config.snippet_characters <= 1_000:
        raise GateEError("snippet_characters must be in [1, 1000]")
    if not math.isfinite(config.max_wall_seconds) or config.max_wall_seconds <= 0:
        raise GateEError("max_wall_seconds must be positive")
    for path in (config.output_dir, config.cache_dir, staging):
        _ensure_git_ignored(path)


def _validate_smoke_config(config: SmokeConfig, staging: Path) -> None:
    _ensure_revision(config.source.revision)
    if not 1 <= config.target_documents <= MAX_SMOKE_DOCUMENTS:
        raise GateEError(f"target_documents must be in [1, {MAX_SMOKE_DOCUMENTS}]")
    if not config.target_documents <= config.max_scanned <= MAX_SMOKE_SCANNED:
        raise GateEError(f"max_scanned must be in [target_documents, {MAX_SMOKE_SCANNED}]")
    if config.stop_after_documents is not None and not (
        1 <= config.stop_after_documents < config.target_documents
    ):
        raise GateEError("stop_after_documents must be positive and below target_documents")
    if not math.isfinite(config.max_wall_seconds) or config.max_wall_seconds <= 0:
        raise GateEError("max_wall_seconds must be positive")
    for path in (
        config.inspection_report,
        config.inspection_report.with_name("review_snippets.jsonl"),
        config.output_dir,
        config.cache_dir,
        staging,
    ):
        _ensure_git_ignored(path)


